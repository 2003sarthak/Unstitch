def probe_payload(**video_overrides: object) -> dict[str, object]:
    video = {
        "codec_type": "video",
        "codec_name": "h264",
        "width": 1080,
        "height": 1920,
        "avg_frame_rate": "30000/1001",
    }
    video.update(video_overrides)
    return {
        "streams": [video, {"codec_type": "audio", "codec_name": "aac"}],
        "format": {"duration": "12.5"},
    }


class TestProbeParsing:
    def test_reads_the_fields_the_pipeline_needs(self) -> None:
        info = parse_probe(Path("clip.mp4"), probe_payload())
        assert (info.width, info.height) == (1080, 1920)
        assert info.duration_s == 12.5
        assert info.video_codec == "h264"
        assert info.has_audio is True
        assert info.fps == pytest.approx(29.97, abs=0.01)

    def test_ntsc_frame_rate_is_a_rational_not_a_decimal(self) -> None:
        assert parse_probe(Path("c.mp4"), probe_payload()).fps != 30.0

    def test_variable_frame_rate_reports_zero_rather_than_dividing_by_zero(self) -> None:
        info = parse_probe(Path("c.mp4"), probe_payload(avg_frame_rate="0/0"))
        assert info.fps == 0.0

    def test_missing_container_duration_falls_back_to_the_stream(self) -> None:
        payload = probe_payload(duration="8.0")
        payload["format"] = {}
        assert parse_probe(Path("c.mp4"), payload).duration_s == 8.0

    def test_missing_video_stream_is_rejected(self) -> None:
        with pytest.raises(ValueError, match="no video stream"):
            parse_probe(Path("audio.m4a"), {"streams": [{"codec_type": "audio"}], "format": {}})

    def test_audio_absence_is_detected(self) -> None:
        payload = probe_payload()
        payload["streams"] = [payload["streams"][0]]  # type: ignore[index]
        assert parse_probe(Path("c.mp4"), payload).has_audio is False


class TestRotation:
    """Phone-shot vertical video stores landscape pixels plus a rotation. Getting
    this wrong would mean every bounding box is expressed against the wrong
    dimensions."""

    def test_display_matrix_rotation_swaps_display_dimensions(self) -> None:
        payload = probe_payload(width=1920, height=1080, side_data_list=[{"rotation": -90}])
        info = parse_probe(Path("c.mp4"), payload)
        assert (info.width, info.height) == (1920, 1080)  # as stored
        assert (info.display_width, info.display_height) == (1080, 1920)  # as seen
        assert info.is_vertical

    def test_negative_and_legacy_rotations_agree(self) -> None:
        """A display matrix reports -90 where the old tag reported 270."""
        matrix = parse_probe(Path("c.mp4"), probe_payload(side_data_list=[{"rotation": -90}]))
        legacy = parse_probe(Path("c.mp4"), probe_payload(tags={"rotate": "270"}))
        assert matrix.rotation == legacy.rotation == 270

    def test_180_rotation_does_not_swap_dimensions(self) -> None:
        info = parse_probe(
            Path("c.mp4"),
            probe_payload(width=1920, height=1080, side_data_list=[{"rotation": 180}]),
        )
        assert (info.display_width, info.display_height) == (1920, 1080)

    def test_no_rotation_metadata_is_zero(self) -> None:
        assert parse_probe(Path("c.mp4"), probe_payload()).rotation == 0


