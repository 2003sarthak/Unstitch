class TestAgainstRealFfmpeg:
    async def test_probe_reads_a_real_file(self, ffmpeg: Ffmpeg, sample_video: Path) -> None:
        info = await ffmpeg.probe(sample_video)
        assert (info.width, info.height) == (320, 240)
        assert info.duration_s == pytest.approx(2.0, abs=0.2)
        assert info.fps == pytest.approx(30.0, abs=0.1)
        assert info.video_codec == "h264"
        assert info.has_audio

    async def test_a_rendered_filter_graph_is_accepted_by_ffmpeg(
        self, ffmpeg: Ffmpeg, sample_video: Path, tmp_path: Path
    ) -> None:
        """The one test that proves our escaping is right.

        The `enable` expression contains commas; if they were not escaped ffmpeg
        would parse them as filter separators and fail. Asserting on the string
        alone could not catch a rule we had simply got wrong.
        """
        out = tmp_path / "masked.mp4"
        graph = FilterGraph(
            [
                FilterChain(
                    [
                        Filter(
                            "delogo", {"x": 10, "y": 10, "w": 80, "h": 40}, enable=between(0.5, 1.5)
                        )
                    ]
                )
            ]
        )
        await ffmpeg.run(["-i", str(sample_video), *graph.to_args(), "-c:a", "copy", str(out)])

        assert out.exists()
        assert (await ffmpeg.probe(out)).duration_s == pytest.approx(2.0, abs=0.2)

    async def test_failure_carries_the_command_and_stderr(self, ffmpeg: Ffmpeg) -> None:
        with pytest.raises(FFmpegError) as excinfo:
            await ffmpeg.run(["-i", "does-not-exist.mp4", "out.mp4"])

        error = excinfo.value
        assert error.returncode != 0
        assert "does-not-exist.mp4" in error.command
        assert error.stderr  # the reason, not just the exit code

    async def test_timeout_kills_the_process(self, tmp_path: Path) -> None:
        """A runaway encode must not outlive its await and keep a core busy."""
        impatient = Ffmpeg(default_timeout_s=0.05)
        with pytest.raises(FFmpegTimeoutError):
            await impatient.run(
                [
                    "-f",
                    "lavfi",
                    "-i",
                    "testsrc2=size=1920x1080:rate=60:duration=60",
                    "-c:v",
                    "libx264",
                    "-preset",
                    "veryslow",
                    str(tmp_path / "slow.mp4"),
                ]
            )
