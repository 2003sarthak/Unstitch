"""Tests for the ffmpeg wrapper.

Split deliberately into two halves:

* Everything about *filter graphs* is pure and runs in microseconds, because
  those are value objects. This is the payoff for not building strings inline -
  the logic that decides what gets erased is testable without media.
* Everything about *running ffmpeg* is an integration test against a clip
  generated by ffmpeg itself (see conftest.py), so the suite carries no binary
  fixtures and still proves the argument lists we build are ones ffmpeg will
  actually accept.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from app.infra.ffmpeg import (
    Ffmpeg,
    FFmpegError,
    FFmpegTimeoutError,
    Filter,
    FilterChain,
    FilterGraph,
    between,
    escape_value,
    parse_probe,
)

# =============================================================================
#  Pure: filter graph construction
# =============================================================================


class TestFilterRendering:
    def test_filter_without_params_is_just_its_name(self) -> None:
        assert Filter("null").render() == "null"

    def test_params_are_colon_separated(self) -> None:
        rendered = Filter("delogo", {"x": 10, "y": 20, "w": 100, "h": 40}).render()
        assert rendered == "delogo=x=10:y=20:w=100:h=40"

    def test_floats_avoid_scientific_notation(self) -> None:
        """`str(1e-05)` is "1e-05", which ffmpeg's expression parser rejects."""
        assert Filter("f", {"v": 0.00001}).render() == "f=v=0"
        assert Filter("f", {"v": 1.5}).render() == "f=v=1.5"
        assert Filter("f", {"v": 2.0}).render() == "f=v=2"

    def test_booleans_render_as_flags_not_python_words(self) -> None:
        assert Filter("f", {"on": True, "off": False}).render() == "f=on=1:off=0"


class TestEscaping:
    @pytest.mark.parametrize(
        ("raw", "escaped"),
        [
            ("between(t,1,2)", "between(t\\,1\\,2)"),
            ("a:b", "a\\:b"),
            ("a;b", "a\\;b"),
            ("[in]", "\\[in\\]"),
            ("it's", "it\\'s"),
            ("back\\slash", "back\\\\slash"),
        ],
    )
    def test_structural_characters_are_escaped(self, raw: str, escaped: str) -> None:
        assert escape_value(raw) == escaped

    def test_escaping_is_single_pass(self) -> None:
        """A backslash already in the value must be escaped once, not twice -
        which is why this uses `str.translate` rather than chained `.replace()`."""
        assert escape_value("a\\,b") == "a\\\\\\,b"

    def test_plain_values_are_untouched(self) -> None:
        assert escape_value("min(ih,720)") == "min(ih\\,720)"
        assert escape_value("veryfast") == "veryfast"


class TestTimeGating:
    def test_between_builds_a_timeline_expression(self) -> None:
        assert between(1.5, 3.25) == "between(t,1.500,3.250)"

    def test_enable_is_escaped_when_rendered(self) -> None:
        """The commas inside the expression must not read as filter separators -
        if they did, ffmpeg would see three filters instead of one."""
        rendered = Filter("delogo", {"x": 1}, enable=between(0.0, 2.0)).render()
        assert rendered == "delogo=x=1:enable=between(t\\,0.000\\,2.000)"


class TestFilterGraph:
    def test_empty_graph_produces_no_arguments(self) -> None:
        """A video with no detected overlays must be passed through, not run
        through an empty graph - ffmpeg rejects one."""
        assert FilterGraph().is_empty
        assert FilterGraph().to_args() == []
        assert FilterGraph([FilterChain([])]).to_args() == []

    def test_single_unlabelled_chain_uses_vf(self) -> None:
        graph = FilterGraph([FilterChain([Filter("scale", {"w": -2, "h": 720})])])
        assert graph.is_simple
        assert graph.to_args() == ["-vf", "scale=w=-2:h=720"]

    def test_labelled_chain_uses_filter_complex(self) -> None:
        graph = FilterGraph(
            [
                FilterChain(
                    [Filter("overlay", {"x": 0, "y": 0})], inputs=["0:v", "1:v"], outputs=["out"]
                )
            ]
        )
        assert not graph.is_simple
        flag, value = graph.to_args()
        assert flag == "-filter_complex"
        assert value == "[0:v][1:v]overlay=x=0:y=0[out]"

    def test_multiple_chains_are_semicolon_separated(self) -> None:
        graph = FilterGraph(
            [
                FilterChain([Filter("scale", {"w": -2, "h": 720})], inputs=["0:v"], outputs=["v0"]),
                FilterChain([Filter("null")], inputs=["v0"], outputs=["out"]),
            ]
        )
        assert graph.render() == "[0:v]scale=w=-2:h=720[v0];[v0]null[out]"

    def test_overlay_removal_chain_matches_the_intended_shape(self) -> None:
        """The shape step 8 will produce: one time-gated `delogo` per detected
        overlay, chained into a single pass over the video."""
        graph = FilterGraph(
            [
                FilterChain(
                    [
                        Filter(
                            "delogo",
                            {"x": 10, "y": 20, "w": 100, "h": 40},
                            enable=between(0.0, 2.5),
                        ),
                        Filter(
                            "delogo",
                            {"x": 5, "y": 600, "w": 300, "h": 80},
                            enable=between(3.0, 7.0),
                        ),
                    ]
                )
            ]
        )
        assert graph.to_args() == [
            "-vf",
            "delogo=x=10:y=20:w=100:h=40:enable=between(t\\,0.000\\,2.500),"
            "delogo=x=5:y=600:w=300:h=80:enable=between(t\\,3.000\\,7.000)",
        ]


